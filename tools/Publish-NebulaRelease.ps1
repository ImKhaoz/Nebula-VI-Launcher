#requires -Version 7.0
[CmdletBinding()]
param(
    [Parameter(Mandatory)][ValidatePattern('^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$')][string]$Version,
    [AllowEmptyString()][ValidatePattern('^$|^[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+$')][string]$Repository = ''
)

$ErrorActionPreference = 'Stop'
$PSNativeCommandUseErrorActionPreference = $true
$root = Split-Path -Parent $PSScriptRoot
$edition = 'Nebula-GTAVI-Version'
$release = Join-Path $root "release/$edition-v$Version"
$name = "$edition-$Version-win-x64"
$app = Join-Path $release $name
if (Test-Path -LiteralPath $release) { throw "Release directory already exists: $release" }

$null = New-Item -ItemType Directory -Path $release
dotnet publish (Join-Path $root 'Nebula-GTAVI.csproj') -c Release -r win-x64 --self-contained true `
    "-p:NebulaVersion=$Version" "-p:NebulaReleaseRepository=$Repository" -o $app

$required = @("$edition.exe", 'Dashboard/index.html', 'Assets/NexusLogo.png')
foreach ($path in $required) {
    if (!(Test-Path -LiteralPath (Join-Path $app $path) -PathType Leaf)) { throw "Missing release file: $path" }
}
foreach ($directory in 'source','diagnostics') {
    if (Test-Path -LiteralPath (Join-Path $app $directory)) { throw "Unexpected release directory: $directory" }
}
$desktopRuntime = Join-Path $app 'runtimes/win-x64/native/WebView2Loader.dll'
$runtimeDirectory = Join-Path $app 'runtimes'
if (Test-Path -LiteralPath $runtimeDirectory) {
    $unexpectedRuntime = Get-ChildItem -LiteralPath $runtimeDirectory -Recurse -File | Where-Object { $_.FullName -ne $desktopRuntime }
    if ($unexpectedRuntime) { throw 'The launcher-only package contains an unexpected runtime file.' }
}
$excluded = Get-ChildItem -LiteralPath $app -Recurse -File | Where-Object {
    $_.Extension -in '.rpf','.xex','.xvc','.pdb' -or
    $_.Name -in 'MicrosoftGame.Config','game_scarlett_master.exe','library.json','settings.json',
        'gtavi-cover.jpg','gtavi-hero.jpg','GtaVi.ico','NexusBackdrop.png','dxil.dll','dxcompiler.dll'
}
# Symbols are generated by the launcher build and are unnecessary in the portable release.
foreach ($file in $excluded) {
    if ($file.Extension -eq '.pdb') { Remove-Item -LiteralPath $file.FullName }
    else { throw "Unexpected release file: $($file.Name)" }
}

foreach ($folder in $app, $release) { Copy-Item -LiteralPath (Join-Path $root 'README.md') -Destination (Join-Path $folder 'README.md') }
$assets = Get-Content -Raw (Join-Path $root 'obj/project.assets.json') | ConvertFrom-Json
$packages = @($assets.packageFolders.PSObject.Properties.Name)
$config = Get-Content -Raw (Join-Path $app "$edition.runtimeconfig.json") | ConvertFrom-Json
if (!$config.runtimeOptions.includedFrameworks -or
    !($config.runtimeOptions.includedFrameworks.name -contains 'Microsoft.NETCore.App') -or
    !($config.runtimeOptions.includedFrameworks.name -contains 'Microsoft.WindowsDesktop.App')) {
    throw 'The published app is framework-dependent. Refusing to package a release that requires users to install the .NET Desktop Runtime.'
}
foreach ($runtimeFile in 'hostfxr.dll','hostpolicy.dll','coreclr.dll','PresentationFramework.dll') {
    if (!(Test-Path -LiteralPath (Join-Path $app $runtimeFile) -PathType Leaf)) {
        throw "The self-contained release is missing $runtimeFile."
    }
}
$licenses = @{
    'microsoft.web.webview2/1.0.4370.26' = 'WebView2'
}
foreach ($framework in $config.runtimeOptions.includedFrameworks) {
    $licenses["$($framework.name.ToLowerInvariant()).runtime.win-x64/$($framework.version)"] = $framework.name
}
foreach ($package in $licenses.Keys) {
    $directory = $packages | ForEach-Object { Join-Path $_ $package } | Where-Object { Test-Path -LiteralPath $_ } | Select-Object -First 1
    if (!$directory) { throw "License package was not found: $package" }
    $destination = Join-Path $app "licenses/$($licenses[$package])"
    $null = New-Item -ItemType Directory -Path $destination -Force
    Get-ChildItem -LiteralPath $directory -File | Where-Object { $_.Name -match '^(license|notice|third-party-notices)(\.txt)?$' } |
        Copy-Item -Destination $destination
}

$archive = Join-Path $release "$name.zip"
[IO.Compression.ZipFile]::CreateFromDirectory($app, $archive, [IO.Compression.CompressionLevel]::Optimal, $true)
$hash = (Get-FileHash -LiteralPath $archive -Algorithm SHA256).Hash.ToLowerInvariant()
"$hash  $name.zip" | Set-Content -LiteralPath (Join-Path $release 'SHA256SUMS.txt')
Write-Host "Release prepared at $release"
if ([string]::IsNullOrWhiteSpace($Repository)) {
    Write-Host 'GitHub update checking is disabled until -Repository OWNER/REPOSITORY is set.'
}
